"""Generate TEST_SPECS/traceability.md: every acceptance criterion and the tests that cover it (ADR-0012).

Usage: uv run python scripts/traceability.py [--check]
--check exits with 1 if any criterion has no test.
"""

import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
AC_RE = re.compile(r"\bAC-([A-Z]+)-(\d+)\b")
TEST_RE = re.compile(r"def (test_AC_([A-Z]+)_(\d+)\w*)\(")


def collect() -> tuple[dict[str, tuple[str, str]], dict[str, list[str]]]:
    criteria: dict[str, tuple[str, str]] = {}
    for spec in sorted((ROOT / "SPECIFICATIONS").glob("*.md")):
        for line in spec.read_text(encoding="utf-8").splitlines():
            if line.startswith("|"):
                m = AC_RE.search(line)
                if m:
                    ac = f"AC-{m.group(1)}-{m.group(2)}"
                    cells = [c.strip() for c in line.strip("|").split("|")]
                    criteria.setdefault(ac, (spec.name, " / ".join(cells[1:4])))
    tests: dict[str, list[str]] = defaultdict(list)
    for f in sorted((ROOT / "tests").rglob("test_*.py")):
        for m in TEST_RE.finditer(f.read_text(encoding="utf-8")):
            tests[f"AC-{m.group(2)}-{m.group(3)}"].append(f"{f.relative_to(ROOT).as_posix()}::{m.group(1)}")
    return criteria, tests


def main() -> int:
    criteria, tests = collect()
    missing = [ac for ac in criteria if ac not in tests]
    lines = ["# Traceability", "", "Generated by `scripts/traceability.py`. Do not edit by hand.", "",
             f"{len(criteria)} acceptance criteria, {len(criteria) - len(missing)} covered by tests.", "",
             "| Criterion | Spec | Tests |", "|---|---|---|"]
    for ac in sorted(criteria, key=lambda a: (a.split("-")[1], int(a.split("-")[2]))):
        spec, _ = criteria[ac]
        covered = "<br>".join(f"`{t.split('::')[1]}`" for t in tests.get(ac, [])) or "**MISSING**"
        lines.append(f"| {ac} | [{spec}](../SPECIFICATIONS/{spec}) | {covered} |")
    (ROOT / "TEST_SPECS" / "traceability.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(criteria)} criteria, {len(missing)} without tests" + (f": {', '.join(missing)}" if missing else ""))
    return 1 if missing and "--check" in sys.argv else 0


if __name__ == "__main__":
    raise SystemExit(main())
